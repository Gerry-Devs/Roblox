local selected = game:GetService("Selection"):Get()[1]
assert(selected, "Select the imported leviathan model in the Explorer first")

local materials = {}
for _, m in ipairs(Enum.Material:GetEnumItems()) do
	materials[m.Value] = m
end

local out = Instance.new("Model")
out.Name = "leviathan"
local found, missing = 0, {}
local seen = {}
for _, part in ipairs(selected:GetDescendants()) do
	if part:IsA("MeshPart") then
		local key = part.Name:match("L%d%d%d")
		local info = key and PIECES[key]
		if info and not seen[key] then
			seen[key] = true
			found += 1
			for _, child in ipairs(part:GetChildren()) do
				child:Destroy() -- SurfaceAppearance etc. from the importer
			end
			part.Size = Vector3.new(info.s[1], info.s[2], info.s[3])
			part.CFrame = CFrame.new(info.p[1], info.p[2], info.p[3])
			part.Color = Color3.fromRGB(info.c[1], info.c[2], info.c[3])
			part.Material = materials[info.m] or Enum.Material.SmoothPlastic
			part.Transparency = info.t
			part.TextureID = ""
			part.Anchored = true
			part.CanCollide = false
			part.CanQuery = false
			part.CanTouch = false
			part.CastShadow = false
			part:SetAttribute("G", info.g)
			part.Name = "Piece"
			part.Parent = out
		end
	end
end
for key in pairs(PIECES) do
	if not seen[key] then
		table.insert(missing, key)
	end
end

local folder = game:GetService("ReplicatedStorage"):WaitForChild("MonsterRNG")
local meshRigs = folder:FindFirstChild("MonsterMeshRigs")
if not meshRigs then
	meshRigs = Instance.new("Folder")
	meshRigs.Name = "MonsterMeshRigs"
	meshRigs.Parent = folder
end
local old = meshRigs:FindFirstChild("leviathan")
if old then
	old:Destroy()
end
out.Parent = meshRigs
selected:Destroy()
game:GetService("ChangeHistoryService"):SetWaypoint("Leviathan mesh rig")
print(("Leviathan mesh rig: %d / %d pieces placed in MonsterMeshRigs.leviathan"):format(found, found + #missing))
if #missing > 0 then
	warn("Missing pieces (not found in the import): " .. table.concat(missing, ", "))
end
